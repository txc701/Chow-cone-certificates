"""Frozen result manifests record the SHA-256 of the source files that produced
them.  Those sources must stay byte-identical; otherwise the manifests have to
be regenerated by rerunning the computations."""
import glob
import hashlib
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")


def _sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def test_sources_pinned_by_frozen_manifests_are_unchanged():
    manifests = sorted(glob.glob(os.path.join(ROOT, "results", "**", "manifest.json"),
                                 recursive=True))
    pinned = {}
    for manifest in manifests:
        with open(manifest) as f:
            doc = json.load(f)
        for entry in doc.get("source_provenance", []):
            assert _sha256(os.path.join(ROOT, entry["path"])) == entry["sha256"], (
                os.path.relpath(manifest, ROOT), entry["path"])
            pinned.setdefault(entry["path"], set()).add(os.path.relpath(manifest, ROOT))
    # the two frozen k=4 manifests both pin the weight module
    assert len(pinned.get("src/k4_weights.py", ())) == 2
    assert len(pinned) >= 8
