"""Implementation 2 of the Cheng-Lin weights: recursive composition generation.

Genuinely independent of src/weights_bitmask.py:

* Subsets are not enumerated; instead all compositions (n_1, ..., n_{m+1}) of
  d+2 with n_i >= 1 and n_{m+1} >= 2 are generated by recursion on the parts.
  (These are in bijection with subsets J <= [d]: J is the set of proper
  prefix sums j_i = n_1 + ... + n_i, i = 1..m, all of which lie in [d]
  exactly because the last part is >= 2.)
* U_J is computed incrementally via binomial coefficients:
  the multinomial M = (d+2)! / prod n_i! is built up as a product of
  math.comb values while parts are chosen, and U_J = M * n_last / (d+2).
* a_J uses the algebraically equivalent form
  a_J = prod (n_i - 1) * ( sum n_i (n_i - 2)  -  (d+2) ) / 2
  (equal because sum n_i = d+2).

Exact integer arithmetic only; divisions are checked.
"""

from math import comb


def _gen(remaining: int, parts: list[int], multinomial: int, out: list) -> None:
    """Extend `parts` (already summing to total-remaining) by all valid tails.

    `multinomial` is comb-product so far: the number of ways to place the
    chosen parts, i.e. (total)! / (prod_{chosen} n_i!) / (remaining)!.
    """
    # close the composition here: last part = remaining, needs >= 2
    if remaining >= 2:
        final_multinomial = multinomial  # times comb(remaining, remaining) == 1
        out.append((tuple(parts + [remaining]), final_multinomial))
    # or add a further non-final part p (leaving >= 2 for the final part... or
    # more parts; leaving >= 1 suffices to recurse, final check handles >= 2)
    for p in range(1, remaining):
        _gen(
            remaining - p,
            parts + [p],
            multinomial * comb(remaining, p),
            out,
        )


def all_compositions_with_multinomial(d: int) -> list[tuple[tuple[int, ...], int]]:
    """All compositions of d+2 with last part >= 2, paired with the
    multinomial coefficient (d+2)! / prod n_i!."""
    out: list = []
    _gen(d + 2, [], 1, out)
    return out


def uaw(parts: tuple[int, ...], multinomial: int, d: int) -> tuple[int, int, int]:
    n = d + 2
    num = multinomial * parts[-1]
    assert num % n == 0, ("U not integral", parts, d)
    u = num // n

    prod = 1
    for p in parts:
        prod *= p - 1
    s = sum(p * (p - 2) for p in parts) - n
    assert s % 2 == 0, ("a not integral", parts, d)
    a = prod * (s // 2)
    return u, a, u * a


def mask_of_composition(parts: tuple[int, ...]) -> int:
    """Subset mask from proper prefix sums of the composition."""
    mask = 0
    acc = 0
    for p in parts[:-1]:
        acc += p
        mask |= 1 << (acc - 1)
    return mask


def weight_map(d: int) -> dict[int, tuple[int, int, int]]:
    """Full map {mask: (U_J, a_J, w_J)}, built from compositions."""
    result: dict[int, tuple[int, int, int]] = {}
    for parts, multinomial in all_compositions_with_multinomial(d):
        mask = mask_of_composition(parts)
        assert mask not in result, ("duplicate mask", parts)
        result[mask] = uaw(parts, multinomial, d)
    assert len(result) == 1 << d, ("wrong count", d, len(result))
    return result
